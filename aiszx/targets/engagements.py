"""Engagement registry: authorisation metadata, validity window and workspace root."""

from __future__ import annotations

import json
import sqlite3
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any

from aiszx.core.audit import record_event
from aiszx.core.errors import NotFoundError, ValidationError
from aiszx.core.fsutil import write_yaml
from aiszx.core.ids import new_id
from aiszx.core.timeutil import iso, parse_bound, parse_iso, utcnow
from aiszx.db.connection import Database
from aiszx.targets.identity import normalise_slug
from aiszx.targets.workspace import WorkspaceLayout

MIRROR_HEADER = "# Generated by Aiszx from its database. Edits to this file are not read back.\n"

ACTIVE = "active"
NOT_YET_VALID = "not_yet_valid"
EXPIRED = "expired"
ARCHIVED = "archived"


@dataclass(frozen=True)
class Engagement:
    id: str
    slug: str
    name: str
    description: str | None
    authorisation_ref: str | None
    valid_from: str | None
    valid_until: str | None
    created_at: str
    updated_at: str
    archived_at: str | None
    roe: dict[str, Any] = field(default_factory=dict)

    @classmethod
    def from_row(cls, row: sqlite3.Row) -> "Engagement":
        return cls(
            id=row["id"],
            slug=row["slug"],
            name=row["name"],
            description=row["description"],
            authorisation_ref=row["authorisation_ref"],
            valid_from=row["valid_from"],
            valid_until=row["valid_until"],
            created_at=row["created_at"],
            updated_at=row["updated_at"],
            archived_at=row["archived_at"],
            roe=json.loads(row["roe_json"] or "{}"),
        )

    def validity(self, now: datetime | None = None) -> str:
        now = now or utcnow()
        if self.archived_at:
            return ARCHIVED
        if self.valid_from and now < parse_iso(self.valid_from):
            return NOT_YET_VALID
        if self.valid_until and now > parse_iso(self.valid_until):
            return EXPIRED
        return ACTIVE

    def to_dict(self) -> dict[str, Any]:
        return {
            "id": self.id,
            "slug": self.slug,
            "name": self.name,
            "description": self.description,
            "authorisation_ref": self.authorisation_ref,
            "valid_from": self.valid_from,
            "valid_until": self.valid_until,
            "validity": self.validity(),
            "rules_of_engagement": self.roe,
            "created_at": self.created_at,
            "updated_at": self.updated_at,
            "archived_at": self.archived_at,
        }


class EngagementStore:
    def __init__(self, db: Database, layout: WorkspaceLayout, actor: str) -> None:
        self.db = db
        self.layout = layout
        self.actor = actor

    def find(self, slug: str) -> Engagement | None:
        row = self.db.query_one("SELECT * FROM engagements WHERE slug = ?", (normalise_slug(slug),))
        return Engagement.from_row(row) if row else None

    def get(self, slug: str) -> Engagement:
        eng = self.find(slug)
        if eng is None:
            raise NotFoundError(f"engagement '{slug}' does not exist; create it with `engagement add {slug}`")
        return eng

    def list(self, include_archived: bool = False) -> list[Engagement]:
        sql = "SELECT * FROM engagements" + ("" if include_archived else " WHERE archived_at IS NULL") + " ORDER BY slug"
        return [Engagement.from_row(r) for r in self.db.query(sql)]

    def create(
        self,
        slug: str,
        *,
        name: str | None = None,
        description: str | None = None,
        authorisation_ref: str | None = None,
        valid_from: str | None = None,
        valid_until: str | None = None,
    ) -> Engagement:
        slug = normalise_slug(slug)
        vf = parse_bound(valid_from, end=False)
        vu = parse_bound(valid_until, end=True)
        if vf and vu and parse_iso(vf) > parse_iso(vu):
            raise ValidationError("--valid-from must not be later than --valid-until")
        if self.find(slug):
            raise ValidationError(f"engagement '{slug}' already exists")
        eid, now = new_id(), iso()
        with self.db.transaction():
            self.db.execute(
                "INSERT INTO engagements (id, slug, name, description, authorisation_ref, valid_from, valid_until,"
                " created_at, updated_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (eid, slug, name or slug, description, authorisation_ref, vf, vu, now, now),
            )
            record_event(self.db, "engagement.create", actor=self.actor, engagement_id=eid, slug=slug)
            self.layout.ensure_engagement(slug)
        eng = self.get(slug)
        self.write_mirror(eng)
        return eng

    def update(
        self,
        slug: str,
        *,
        name: str | None = None,
        description: str | None = None,
        authorisation_ref: str | None = None,
        valid_from: str | None = None,
        valid_until: str | None = None,
        max_safety: str | None = None,
        clear: tuple[str, ...] = (),
    ) -> Engagement:
        """Update metadata. ``clear`` may contain valid_from, valid_until, max_safety."""
        eng = self.get(slug)
        fields: dict[str, object] = {}
        if name is not None:
            fields["name"] = name
        if description is not None:
            fields["description"] = description
        if authorisation_ref is not None:
            fields["authorisation_ref"] = authorisation_ref
        if valid_from is not None:
            fields["valid_from"] = parse_bound(valid_from, end=False)
        if valid_until is not None:
            fields["valid_until"] = parse_bound(valid_until, end=True)
        for key in ("valid_from", "valid_until"):
            if key in clear:
                fields[key] = None
        roe = dict(eng.roe)
        if max_safety is not None:
            from aiszx.modules.base import Safety

            allowed = [s.value for s in Safety if s is not Safety.PROHIBITED_AUTO]
            if max_safety not in allowed:
                raise ValidationError(f"--max-safety must be one of {', '.join(allowed)}")
            roe["max_safety"] = max_safety
        if "max_safety" in clear:
            roe.pop("max_safety", None)
        if roe != eng.roe:
            fields["roe_json"] = json.dumps(roe, sort_keys=True)
        vf = fields.get("valid_from", eng.valid_from)
        vu = fields.get("valid_until", eng.valid_until)
        if vf and vu and parse_iso(str(vf)) > parse_iso(str(vu)):
            raise ValidationError("valid_from must not be later than valid_until")
        if not fields:
            return eng
        fields["updated_at"] = iso()
        with self.db.transaction():
            sets = ", ".join(f"{k} = ?" for k in fields)
            self.db.execute(f"UPDATE engagements SET {sets} WHERE id = ?", [*fields.values(), eng.id])
            record_event(self.db, "engagement.update", actor=self.actor, engagement_id=eng.id,
                         changes={k: v for k, v in fields.items() if k != "updated_at"})
        updated = self.get(slug)
        self.write_mirror(updated)
        return updated

    def ensure(self, slug: str) -> tuple[Engagement, bool]:
        existing = self.find(slug)
        if existing:
            self.layout.ensure_engagement(existing.slug)
            return existing, False
        return self.create(slug, name="Default engagement" if slug == "default" else None), True

    def write_mirror(self, eng: Engagement) -> None:
        write_yaml(self.layout.engagement_dir(eng.slug) / "engagement.yaml", eng.to_dict(), MIRROR_HEADER)
